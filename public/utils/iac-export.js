/**
 * Infrastructure-as-Code Export Utilities
 *
 * Generates Terraform (Junos provider) and Ansible (junos_config) output
 * from SRX set commands. Parses the set command output and produces
 * structured IaC artifacts.
 */
import { BRAND } from './brand.js';

/**
 * Generates Terraform HCL configuration using the Junos Terraform provider.
 *
 * The global address book becomes one `junos_security_address_book` resource
 * (all-or-nothing, like zones: any unmapped global line keeps it raw; zone-scoped
 * books always stay raw). Zones become `junos_security_zone` resources and each from/to zone pair
 * becomes one `junos_security_policy` (the provider keys it by zone pair, with
 * an ordered policy list). A zone pair is structured only when every one of its
 * lines maps to a provider attribute and none is deactivated; otherwise all its
 * lines are loaded verbatim. Everything else goes to a `junos_null_load_config`
 * resource in original command order.
 * @param {string[]} commands - Array of SRX set commands
 * @param {Object} [options] - Export options
 * @param {string} [options.providerHost] - SRX device hostname/IP
 * @returns {string} Terraform HCL configuration
 */
export function exportToTerraform(commands, options = {}) {
  const host = options.providerHost || 'srx.example.com';
  const lines = [];

  // Provider block
  lines.push('# =============================================');
  lines.push('# Terraform Configuration for Juniper SRX');
  lines.push(`# Generated by ${BRAND.accessibleName}`);
  lines.push('# =============================================');
  lines.push('');
  lines.push('terraform {');
  lines.push('  required_providers {');
  lines.push('    junos = {');
  lines.push('      source  = "jeremmfr/junos"');
  lines.push('      version = ">= 2.0.0"');
  lines.push('    }');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('provider "junos" {');
  lines.push(`  ip         = var.srx_host`);
  lines.push('  username   = var.srx_username');
  lines.push('  password   = var.srx_password');
  lines.push('  port       = var.srx_port');
  lines.push('  ssh_key    = var.srx_ssh_key');
  lines.push('}');
  lines.push('');
  lines.push('# --- Variables ---');
  lines.push('variable "srx_host" {');
  lines.push(`  default = "${escapeHcl(host)}"`);
  lines.push('}');
  lines.push('variable "srx_username" { default = "admin" }');
  lines.push('variable "srx_password" { sensitive = true }');
  lines.push('variable "srx_port" { default = 830 }');
  lines.push('variable "srx_ssh_key" { default = "" }');
  lines.push('');

  // Parse commands into groups
  const groups = groupSetCommands(commands);

  // Security zones
  const zoneResources = [];
  const takenZoneNames = new Set();
  for (const zone of groups.zones) {
    const resourceName = uniqueResourceName(zone.name, takenZoneNames);
    zoneResources.push(`junos_security_zone.${resourceName}`);
    lines.push(`# --- Security Zone: ${zone.name} ---`);
    lines.push(`resource "junos_security_zone" "${resourceName}" {`);
    lines.push(`  name = "${escapeHcl(zone.name)}"`);
    for (const iface of zone.interfaces) {
      lines.push(`  interface {`);
      lines.push(`    name = "${escapeHcl(iface)}"`);
      lines.push(`  }`);
    }
    lines.push('}');
    lines.push('');
  }

  // Global address book: one resource, referenced by policies and raw lines.
  const addressBookResources = [];
  const book = groups.addressBook;
  if (book) {
    addressBookResources.push('junos_security_address_book.global');
    lines.push('# --- Address Book: global ---');
    lines.push('resource "junos_security_address_book" "global" {');
    lines.push('  name = "global"');
    for (const address of book.addresses) {
      lines.push(`  ${address.block} {`);
      lines.push(`    name = "${escapeHcl(address.name)}"`);
      for (const [attribute, value] of address.attributes) lines.push(`    ${attribute} = ${value}`);
      if (address.description !== null) lines.push(`    description = "${escapeHcl(address.description)}"`);
      lines.push('  }');
    }
    for (const set of book.sets) {
      lines.push('  address_set {');
      lines.push(`    name = "${escapeHcl(set.name)}"`);
      if (set.addresses.length > 0) lines.push(`    address = ${toHclList(set.addresses)}`);
      if (set.sets.length > 0) lines.push(`    address_set = ${toHclList(set.sets)}`);
      if (set.description !== null) lines.push(`    description = "${escapeHcl(set.description)}"`);
      lines.push('  }');
    }
    lines.push('}');
    lines.push('');
  }

  // Everything not structured, in original order. Applied after the zones and
  // before the policies, which reference the objects defined here.
  const hasRawBlock = groups.remaining.length > 0;
  if (hasRawBlock) {
    lines.push('# --- Additional Configuration (set commands) ---');
    for (const note of groups.rawNotes) lines.push(`# ${note}`);
    lines.push('resource "junos_null_load_config" "additional" {');
    lines.push('  action = "set"');
    lines.push('  config = join("\\n", [');
    for (const cmd of groups.remaining) {
      lines.push(`    "${escapeHcl(cmd)}",`);
    }
    lines.push('  ])');
    const rawDependencies = [...zoneResources, ...addressBookResources];
    if (rawDependencies.length > 0) {
      lines.push(`  depends_on = [${rawDependencies.join(', ')}]`);
    }
    lines.push('}');
    lines.push('');
  }

  // One resource per zone pair: the provider ID is <from_zone>_-_<to_zone>.
  const policyDependencies = [...zoneResources, ...addressBookResources];
  if (hasRawBlock) policyDependencies.push('junos_null_load_config.additional');
  const takenPolicyNames = new Set();
  for (const pair of groups.zonePairs) {
    const resourceName = uniqueResourceName(`${pair.fromZone}_to_${pair.toZone}`, takenPolicyNames);
    lines.push(`# --- Security Policies: ${pair.fromZone} -> ${pair.toZone} ---`);
    lines.push(`resource "junos_security_policy" "${resourceName}" {`);
    lines.push(`  from_zone = "${escapeHcl(pair.fromZone)}"`);
    lines.push(`  to_zone   = "${escapeHcl(pair.toZone)}"`);
    for (const policy of pair.policies) {
      lines.push('  policy {');
      lines.push(`    name                      = "${escapeHcl(policy.name)}"`);
      lines.push(`    match_source_address      = ${toHclList(policy.srcAddrs)}`);
      lines.push(`    match_destination_address = ${toHclList(policy.dstAddrs)}`);
      if (policy.apps.length > 0) lines.push(`    match_application         = ${toHclList(policy.apps)}`);
      if (policy.srcExcluded) lines.push('    match_source_address_excluded      = true');
      if (policy.dstExcluded) lines.push('    match_destination_address_excluded = true');
      lines.push(`    then                      = "${policy.action}"`);
      if (policy.logInit) lines.push('    log_init  = true');
      if (policy.logClose) lines.push('    log_close = true');
      if (policy.count) lines.push('    count     = true');
      if (policy.description !== null) lines.push(`    description = "${escapeHcl(policy.description)}"`);
      const services = Object.entries(policy.appServices);
      if (services.length > 0) {
        lines.push('    permit_application_services {');
        for (const [attribute, value] of services) {
          lines.push(`      ${attribute} = "${escapeHcl(value)}"`);
        }
        lines.push('    }');
      }
      lines.push('  }');
    }
    if (policyDependencies.length > 0) {
      lines.push(`  depends_on = [${policyDependencies.join(', ')}]`);
    }
    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Generates Ansible playbook YAML using junos_config module.
 * @param {string[]} commands - Array of SRX set commands
 * @param {Object} [options] - Export options
 * @param {string} [options.host] - Target host
 * @returns {string} Ansible playbook YAML
 */
export function exportToAnsible(commands, options = {}) {
  const host = options.host || 'srx.example.com';
  const filteredCommands = commands.filter(c =>
    c.startsWith('set ') || c.startsWith('deactivate ')
  );

  const lines = [];
  lines.push('# =============================================');
  lines.push('# Ansible Playbook for Juniper SRX Configuration');
  lines.push(`# Generated by ${BRAND.accessibleName}`);
  lines.push('# =============================================');
  lines.push('---');
  lines.push('- name: Deploy SRX configuration');
  lines.push(`  hosts: ${host}`);
  lines.push('  gather_facts: false');
  lines.push('  connection: netconf');
  lines.push('');
  lines.push('  vars:');
  lines.push('    ansible_network_os: junos');
  lines.push('    ansible_user: "{{ srx_username | default(\'admin\') }}"');
  lines.push('    ansible_password: "{{ srx_password }}"');
  lines.push('    ansible_port: "{{ srx_port | default(830) }}"');
  lines.push('');
  lines.push('  tasks:');
  lines.push('    - name: Apply SRX configuration');
  lines.push('      junipernetworks.junos.junos_config:');
  lines.push('        lines:');

  for (const cmd of filteredCommands) {
    lines.push(`          - "${escapeYaml(cmd)}"`);
  }

  lines.push('        confirm_commit: true');
  lines.push(`        comment: "Applied by ${BRAND.accessibleName}"`);
  lines.push('');
  lines.push('    - name: Verify configuration');
  lines.push('      junipernetworks.junos.junos_command:');
  lines.push('        commands:');
  lines.push('          - show security policies');
  lines.push('          - show security zones');
  lines.push('      register: verify_output');
  lines.push('');
  lines.push('    - name: Display verification');
  lines.push('      debug:');
  lines.push('        var: verify_output.stdout_lines');

  return lines.join('\n');
}

// --- Internal helpers ---

/** Sanitize a name for use as a Terraform resource name */
function sanitizeResourceName(name) {
  return name.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^(\d)/, '_$1').toLowerCase();
}

/** Sanitize a name and suffix it until it is not in `taken` (distinct names can collapse to one). */
function uniqueResourceName(name, taken) {
  const base = sanitizeResourceName(name);
  let candidate = base;
  for (let suffix = 2; taken.has(candidate); suffix++) candidate = `${base}_${suffix}`;
  taken.add(candidate);
  return candidate;
}

/** Escape string for an HCL quoted string; neutralizes `${` and `%{` template sequences. */
function escapeHcl(str) {
  return (str || '')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')
    .replace(/\$\{/g, () => '$${')
    .replace(/%\{/g, () => '%%{');
}

/** Escape string for YAML */
function escapeYaml(str) {
  return (str || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** Convert array to HCL list format */
function toHclList(arr) {
  if (!arr || arr.length === 0) return '["any"]';
  return '[' + arr.map(v => `"${escapeHcl(v)}"`).join(', ') + ']';
}

const BOOK_LINE = /^(set|deactivate) security address-book global(?:\s|$)/;
const BOOK_ENTRY = /^set security address-book global (address|address-set) (\S+) (.+)$/;
const BOOK_ADDRESS_FORMS = [
  [/^(?:\d{1,3}(?:\.\d{1,3}){3}|[0-9a-fA-F:]*:[0-9a-fA-F:.]*)\/\d{1,3}$/, 'network_address', match => [['value', match[0]]]],
  // Junos accepts a bare host; the provider value needs the prefix.
  [/^\d{1,3}(?:\.\d{1,3}){3}$/, 'network_address', match => [['value', `${match[0]}/32`]]],
  [/^[0-9a-fA-F:]*:[0-9a-fA-F:.]*$/, 'network_address', match => [['value', `${match[0]}/128`]]],
  [/^range-address (\S+) to (\S+)$/, 'range_address', match => [['from', match[1]], ['to', match[2]]]],
  [/^wildcard-address (\S+)$/, 'wildcard_address', match => [['value', match[1]]]],
  [/^dns-name (\S+?)(?: (ipv4-only|ipv6-only))?$/, 'dns_name', match => [
    ['value', match[1]], ...(match[2] ? [[match[2].replace('-', '_'), true]] : []),
  ]],
];

/** Parse a Junos description argument (quoted or bare); null when it is neither. */
function parseDescription(text) {
  const quoted = text.match(/^description "((?:[^"\\]|\\.)*)"$/);
  if (quoted) return quoted[1].replace(/\\(.)/g, '$1');
  const bare = text.match(/^description (\S+)$/);
  return bare ? bare[1] : null;
}

/**
 * Apply one global address-book line to `book`.
 * @returns {boolean} false when the line has no junos_security_address_book equivalent
 */
function applyAddressBookLine(book, cmd) {
  const entry = cmd.match(BOOK_ENTRY);
  if (!entry || entry[2].includes('"')) return false;
  const [, kind, name, rest] = entry;
  const description = parseDescription(rest);
  if (kind === 'address-set') {
    const set = book.setMap[name] || (book.setMap[name] = { name, addresses: [], sets: [], description: null });
    if (!book.sets.includes(set)) book.sets.push(set);
    const member = rest.match(/^(address|address-set) (\S+)$/);
    if (member && !member[2].includes('"')) set[member[1] === 'address' ? 'addresses' : 'sets'].push(member[2]);
    else if (description !== null && set.description === null) set.description = description;
    else return false;
    return true;
  }
  const address = book.addressMap[name] || (book.addressMap[name] = { name, block: null, attributes: [], description: null });
  if (!book.addresses.includes(address)) book.addresses.push(address);
  if (description !== null) {
    if (address.description !== null) return false;
    address.description = description;
    return true;
  }
  if (address.block) return false;
  for (const [pattern, block, toAttributes] of BOOK_ADDRESS_FORMS) {
    const match = rest.match(pattern);
    if (!match) continue;
    address.block = block;
    address.attributes = toAttributes(match).map(([attribute, value]) => [
      attribute, value === true ? 'true' : `"${escapeHcl(value)}"`,
    ]);
    return true;
  }
  return false;
}

const POLICY_LINE = /^set security policies from-zone (\S+) to-zone (\S+) policy (\S+)\s+(.+)$/;
const POLICY_DEACTIVATE = /^deactivate security policies from-zone (\S+) to-zone (\S+)(?:\s|$)/;
const APP_SERVICE_ATTRIBUTES = {
  'utm-policy': 'utm_policy',
  'idp-policy': 'idp_policy',
  'security-intelligence-policy': 'security_intelligence_policy',
};

/**
 * Apply one policy body line (the text after `policy <name> `) to a policy record.
 * @returns {boolean} false when the line has no Terraform equivalent
 */
function applyPolicyLine(policy, rest) {
  let match;
  if ((match = rest.match(/^match source-address (\S+)$/))) policy.srcAddrs.push(match[1]);
  else if ((match = rest.match(/^match destination-address (\S+)$/))) policy.dstAddrs.push(match[1]);
  else if ((match = rest.match(/^match application (\S+)$/))) policy.apps.push(match[1]);
  else if (rest === 'match source-address-excluded') policy.srcExcluded = true;
  else if (rest === 'match destination-address-excluded') policy.dstExcluded = true;
  else if ((match = rest.match(/^then (permit|deny|reject)$/))) {
    if (policy.action && policy.action !== match[1]) return false;
    policy.action = match[1];
  } else if (rest === 'then log session-init') policy.logInit = true;
  else if (rest === 'then log session-close') policy.logClose = true;
  else if (rest === 'then count') policy.count = true;
  else if ((match = rest.match(/^description "((?:[^"\\]|\\.)*)"$/))) policy.description = match[1].replace(/\\(.)/g, '$1');
  else if ((match = rest.match(/^description (\S+)$/))) policy.description = match[1];
  else if ((match = rest.match(/^then permit application-services (utm-policy|idp-policy|security-intelligence-policy) (\S+)$/))) {
    policy.appServices[APP_SERVICE_ATTRIBUTES[match[1]]] = match[2];
  } else return false;
  return true;
}

/**
 * Parse set commands into structured groups for Terraform resource generation.
 * A zone pair is structured only if every one of its lines maps to a
 * junos_security_policy attribute and none is deactivated; otherwise all its
 * lines stay in `remaining` (original order) so nothing is dropped.
 */
function groupSetCommands(commands) {
  const zones = [];
  const zoneMap = Object.create(null); // prototype-free: a zone or policy may be named "constructor"
  const pairs = [];
  const pairMap = Object.create(null);
  const book = {
    addresses: [], addressMap: Object.create(null), sets: [], setMap: Object.create(null), rawReason: null,
  };
  const items = []; // { cmd, pair?, zone?, book? } in input order; neither for plain raw lines

  const pairFor = (fromZone, toZone) => {
    const key = `${fromZone}\u0000${toZone}`;
    if (!pairMap[key]) {
      pairMap[key] = { fromZone, toZone, policies: [], policyMap: Object.create(null), rawReason: null };
      pairs.push(pairMap[key]);
    }
    return pairMap[key];
  };

  for (const cmd of commands) {
    if (!cmd.startsWith('set ') && !cmd.startsWith('deactivate ')) continue;

    // junos_security_zone owns the whole zone stanza, so a zone with any other line stays raw entirely
    const zoneMatch = cmd.match(/^(set|deactivate) security zones security-zone (\S+)(?:\s+(.+))?$/);
    if (zoneMatch) {
      const [, verb, zoneName, zoneRest] = zoneMatch;
      if (!zoneMap[zoneName]) {
        zoneMap[zoneName] = { name: zoneName, interfaces: [], rawReason: null };
        zones.push(zoneMap[zoneName]);
      }
      const zone = zoneMap[zoneName];
      const interfaceMatch = verb === 'set' && zoneRest && zoneRest.match(/^interfaces (\S+)$/);
      if (interfaceMatch) zone.interfaces.push(interfaceMatch[1]);
      else if (verb !== 'set' || zoneRest) zone.rawReason = zone.rawReason || `unmapped line "${verb} ${zoneRest || ''}"`;
      items.push({ cmd, zone });
      continue;
    }

    // Only the global book is structured; zone-scoped books stay raw.
    if (BOOK_LINE.test(cmd)) {
      if (!applyAddressBookLine(book, cmd)) book.rawReason = book.rawReason || `unmapped line "${cmd}"`;
      items.push({ cmd, book });
      continue;
    }

    const deactivateMatch = cmd.match(POLICY_DEACTIVATE);
    if (deactivateMatch) {
      const pair = pairFor(deactivateMatch[1], deactivateMatch[2]);
      pair.rawReason = pair.rawReason || 'contains deactivated policy';
      items.push({ cmd, pair });
      continue;
    }

    const policyMatch = cmd.match(POLICY_LINE);
    if (!policyMatch) {
      items.push({ cmd, pair: null });
      continue;
    }
    const [, fromZone, toZone, policyName, rest] = policyMatch;
    const pair = pairFor(fromZone, toZone);
    items.push({ cmd, pair });
    if (!pair.policyMap[policyName]) {
      pair.policyMap[policyName] = {
        name: policyName, srcAddrs: [], dstAddrs: [], apps: [], action: null,
        srcExcluded: false, dstExcluded: false, logInit: false, logClose: false,
        count: false, description: null, appServices: {},
      };
      pair.policies.push(pair.policyMap[policyName]);
    }
    if (!applyPolicyLine(pair.policyMap[policyName], rest)) {
      pair.rawReason = pair.rawReason || `policy ${policyName} has unmapped line "${rest}"`;
    }
  }

  // The provider defaults `then` to permit; a policy without an action must not become one.
  for (const pair of pairs) {
    const actionless = pair.policies.find(policy => !policy.action);
    if (actionless) pair.rawReason = pair.rawReason || `policy ${actionless.name} has no then action`;
  }

  // An address with no value (description only) cannot be a provider block.
  if (book.addresses.some(address => !address.block)) book.rawReason = book.rawReason || 'address without a value';
  // Terraform never removes raw lines, so a managed book referenced by one could not drop or rename
  // that entry later (Junos rejects the dangling reference). Such a book stays raw too.
  if (!book.rawReason) {
    const bookNames = new Set([...book.addresses, ...book.sets].map(entry => entry.name));
    const referencing = items.find(({ cmd, pair, zone, book: itemBook }) => {
      const owner = pair || zone;
      if (itemBook || (owner && !owner.rawReason)) return false;
      return cmd.split(/\s+/).some(token => bookNames.has(token.replace(/^"|"$/g, '')));
    });
    if (referencing) book.rawReason = `referenced by raw command "${referencing.cmd}"`;
  }
  const hasBookLines = items.some(item => item.book);

  // Raw zones and zone pairs keep every line, in place among the other raw commands.
  const remaining = items
    .filter(({ pair, zone, book: itemBook }) => {
      const owner = pair || zone || itemBook;
      return !owner || owner.rawReason;
    })
    .map(({ cmd }) => cmd);
  const rawNotes = [
    ...zones.filter(zone => zone.rawReason)
      .map(zone => `Zone ${zone.name} exported as raw set commands: ${zone.rawReason}`),
    ...(book.rawReason ? [`Global address book exported as raw set commands: ${book.rawReason}`] : []),
    ...pairs.filter(pair => pair.rawReason)
      .map(pair => `Zone pair ${pair.fromZone} -> ${pair.toZone} exported as raw set commands: ${pair.rawReason}`),
  ].map(note => note.replace(/[\r\n]+/g, ' '));
  return {
    zones: zones.filter(zone => !zone.rawReason),
    addressBook: hasBookLines && !book.rawReason ? book : null,
    zonePairs: pairs.filter(pair => !pair.rawReason),
    remaining,
    rawNotes,
  };
}
